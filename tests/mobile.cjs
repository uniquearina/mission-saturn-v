const { chromium } = require("playwright-core");
const OUT = process.env.S;
(async () => {
  const b = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
  const ctx = await b.newContext({ locale: "ru-RU", viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const p = await ctx.newPage();
  const errs = []; p.on("pageerror", (e) => errs.push(e.message));
  await p.goto("http://localhost:8765/");
  await p.evaluate(() => localStorage.clear()); await p.reload();
  console.log("touch detected:", await p.evaluate(() => G.touch));
  await p.waitForFunction(() => G.python.ready, null, { timeout: 60000 });
  await p.evaluate(() => G.voice.setMuted(true));
  await p.screenshot({ path: OUT + "/m-boot.png" });
  await p.tap("#btn-start"); await p.fill("#inp-name", "Миша"); await p.tap("#form-name button");
  await p.waitForSelector("#briefing:not([hidden])");
  await p.screenshot({ path: OUT + "/m-brief.png" });
  while (await p.isVisible("#briefing")) await p.tap("#bf-next");
  await p.waitForTimeout(300);
  await p.screenshot({ path: OUT + "/m-check-bay.png" });
  const d = await p.locator("#scene .drone").boundingBox(); await p.touchscreen.tap(d.x + d.width / 2, d.y + d.height / 2); await p.waitForTimeout(400);
  await p.tap(".tile"); await p.waitForTimeout(400);
  console.log("bubble on keys step:", await p.textContent("#spot-text"), "| keys hidden:", await p.evaluate(() => document.getElementById("spot-keys").hidden));
  await p.screenshot({ path: OUT + "/m-check-keys.png" });
  await p.tap(".CodeMirror"); await p.keyboard.press("End"); await p.keyboard.press("Enter"); await p.keyboard.type("left(");
  await p.waitForTimeout(300);
  await p.tap("#btn-run");
  await p.waitForFunction(() => document.getElementById("tb-num").textContent === "Миссия 1 из 11", null, { timeout: 20000 });
  await p.waitForSelector("#intro:not([hidden])");
  await p.screenshot({ path: OUT + "/m-intro1.png" });
  await p.tap("#in-next"); await p.waitForTimeout(2500);
  await p.screenshot({ path: OUT + "/m-intro2.png" });
  await p.waitForFunction(() => !document.getElementById("in-next").disabled, null, { timeout: 20000 });
  await p.tap("#in-next"); await p.waitForTimeout(300);
  // Умные кавычки
  await p.evaluate(() => { G.debug.editor.set(""); G.debug.editor.cm.replaceSelection("print(“ЦУП, приём”)"); });
  console.log("smart quotes fixed:", JSON.stringify(await p.evaluate(() => G.debug.editor.value)));
  await p.tap("#btn-run"); await p.waitForSelector("#dlg-success:not([hidden])", { timeout: 20000 });
  await p.tap("#btn-next"); await p.waitForSelector("#intro:not([hidden])");
  await p.tap("#in-next"); await p.waitForFunction(() => !document.getElementById("in-next").disabled, null, { timeout: 20000 }); await p.tap("#in-next");
  await p.waitForTimeout(300);
  await p.screenshot({ path: OUT + "/m-mission2.png", fullPage: true });
  console.log("overflow px (game):", await p.evaluate(() => document.documentElement.scrollWidth - innerWidth));
  await p.evaluate(() => document.getElementById("btn-home").click());
  await p.waitForSelector("#screen-home:not([hidden])");
  await p.screenshot({ path: OUT + "/m-home.png", fullPage: true });
  console.log("overflow px (home):", await p.evaluate(() => document.documentElement.scrollWidth - innerWidth), "| errors:", errs);
  await b.close();
})().catch((e) => { console.error(e.message); process.exit(1); });
