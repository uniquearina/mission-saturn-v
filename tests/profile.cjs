const { chromium } = require("playwright-core");
(async () => {
  const b = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
  const p = await b.newPage({ locale: "ru-RU", viewport: { width: 1366, height: 820 } });
  const errs = []; p.on("pageerror", (e) => errs.push(e.message));
  await p.goto("http://localhost:8765/");
  await p.evaluate(() => localStorage.setItem("saturn5.progress.v1", JSON.stringify({ callsign: "Орёл", done: [1, 2, 3], current: 4, onboarded: true })));
  await p.reload(); await p.waitForFunction(() => G.python.ready, null, { timeout: 60000 });
  await p.evaluate(() => G.voice.setMuted(true));
  await p.click("#btn-start");
  console.log("1 old player without name → name screen:", await p.isVisible("#screen-name"));
  await p.fill("#inp-name", "Миша"); await p.click("#form-name button");
  await p.waitForSelector("#screen-home:not([hidden])");
  console.log("1b home:", await p.textContent("#btn-continue"), "|", await p.textContent("#home-call"));
  await p.click("#btn-continue");
  await p.waitForSelector("#intro:not([hidden])"); await p.click("#in-next");
  await p.waitForFunction(() => !document.getElementById("in-next").disabled, null, { timeout: 30000 }); await p.click("#in-next");
  console.log("2 topbar:", await p.textContent("#btn-profile"));
  await p.click("#btn-profile");
  console.log("3 profile:", await p.inputValue("#inp-pf-name"), "/", await p.textContent("#pf-progress"));
  await p.screenshot({ path: process.env.S + "/profile.png" });
  await p.fill("#inp-pf-name", "Миша Г."); await p.click("#form-profile button[type=submit]");
  console.log("4 renamed → topbar:", await p.textContent("#tb-kid"), "| drone tag:", await p.textContent("#scene .drone-tag"), "| stored:", await p.evaluate(() => JSON.parse(localStorage.getItem("saturn5.progress.v1")).name));
  await p.click("#btn-profile"); await p.click("#btn-pf-restart");
  console.log("5 confirm:", await p.textContent("#pf-confirm-text"));
  await p.screenshot({ path: process.env.S + "/profile-confirm.png" });
  await p.click("#btn-pf-no"); console.log("6 cancel → main visible:", await p.isVisible("#pf-main"));
  await p.click("#btn-pf-restart"); await p.click("#btn-pf-yes");
  await p.waitForTimeout(300);
  console.log("7 restarted → briefing:", await p.isVisible("#briefing"), "| progress:", await p.evaluate(() => localStorage.getItem("saturn5.progress.v1")));
  while (await p.isVisible("#briefing")) await p.click("#bf-next");
  await p.waitForTimeout(300);
  await p.click("#dlg-profile [data-close]").catch(() => {});
  await b.close();
  console.log("errors:", errs);
})().catch((e) => { console.error(e.message); process.exit(1); });
